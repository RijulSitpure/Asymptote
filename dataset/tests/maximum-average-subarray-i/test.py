import json, os, re

def load_problem():
    base = os.path.dirname(os.path.abspath(__file__))
    prob_path = os.path.join(base, '..', '..', 'problems', 'maximum-average-subarray-i.json')
    with open(prob_path, 'r', encoding='utf-8') as f:
        return json.load(f)

def extract_hint_code(prob):
    m = re.search(r'```python\n(.*?)\n```', prob['hints'][3]['text'], re.DOTALL)
    if not m: raise ValueError("Could not extract Python code")
    return m.group(1)

def main():
    prob = load_problem()
    sol_code = prob['solutions'][0]['code']
    hint_code = extract_hint_code(prob)
    assert sol_code.strip() == hint_code.strip(), "Hint 4 code must match solution code"

    scope = {'List': list, 'Optional': None}
    exec(sol_code, scope)

    sol = scope['Solution']()
    assert abs(sol.findMaxAverage([1,12,-5,-6,50,3], 4) - 12.75) < 1e-5
    assert abs(sol.findMaxAverage([5], 1) - 5.0) < 1e-5
    print("✓ maximum-average-subarray-i passed")

if __name__ == '__main__':
    main()
